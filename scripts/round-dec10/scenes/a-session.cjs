// A. The tester's session page (Ana): the one-line stop, refusals for good, red mistakes, the block lines, the questions-changed stop.
/* eslint-disable */
const X = require("../lib.cjs");
const { pause, center, lines, waitLive, waitPulse, apiEdit } = X;
const { pair, both, SEND, ALERTS, REQ, noraEdits, toTop, fillRequest, noraEndsEarly , editRace } = require("../common.cjs");

module.exports = (scene) => {
  // ---------- A1: Send Answers stopped once by Nora's edit; the line survives the Alerts toggle and a live redraw; clear-then-reappear; everything at once ----------
  scene("a1", async () => {
    const p = await pair();
    const { N, A } = await both(p, `/app/tests/${p.t}`, `/app/sessions/${p.s}`);
    const D = X.duo("a1-send-answers-stop-line", "Session page · Send Answers: the one-line stop, kept, cleared and back");
    D.start([N, A]);
    await center(A, "#written");
    await pause(A, 2500);
    D.say("Ana types her answers. Her page loaded before Nora's next change.");
    await X.typeIn(A, "#a0", X.ANS[0], 10);
    await X.typeIn(A, "#a1", X.ANS[1], 10);
    await pause(A, 800);
    await editRace(D, N, A, p.t, undefined, "Nora edits the listing in her window (Edit, What should testers do?, Save).");
    D.say("Ana presses Send Answers before her page updates.");
    await center(A, SEND);
    await A.locator(SEND).click();
    await A.waitForSelector("[data-stop-line]", { timeout: 15000 }).catch(() => console.log("   ! no stop line"));
    await pause(A, 800);
    D.say("Stopped once: ONE blue line under the button. Nora's change went into the updates box at the top at once.");
    await lines(A, "a1 first press");
    await pause(A, 3500);
    await toTop(A);
    await center(A, SEND);
    await pause(A, 2000);
    D.say("Ana turns her Alerts off, then on again: the line under Send Answers stays.");
    const alerts = A.locator(ALERTS).first();
    await alerts.scrollIntoViewIfNeeded().catch(() => {});
    await pause(A, 800);
    await alerts.click().catch((e) => console.log("   ! Alerts:", e.message.split("\n")[0]));
    await pause(A, 2500);
    await alerts.click().catch(() => {});
    await pause(A, 2000);
    await center(A, SEND);
    await pause(A, 2500);
    await lines(A, "a1 after Alerts");
    D.say("Nora changes the listing again (its build link, off camera): Ana's page redraws live. The line still stays.");
    await apiEdit(p.nora, p.t, { buildUrl: "https://example.com/harbor-run-2" });
    await N.reload();
    await waitPulse(A, 30000);
    await pause(A, 3000);
    await toTop(A, 3000);
    await center(A, SEND);
    await pause(A, 2000);
    await lines(A, "a1 after live redraw");
    D.say("Ana shortens her first answer to 12 characters and presses Send Answers again.");
    await A.fill("#a0", "");
    await X.typeIn(A, "#a0", "Too short ok", 60);
    await pause(A, 800);
    await A.locator(SEND).click();
    await pause(A, 3500);
    D.say("Clear, then the new outcome: the blue line is gone (this was the second press) and the red mistake shows at the box.");
    await lines(A, "a1 second press (short)");
    await pause(A, 4000);
    await editRace(D, N, A, p.t, " Then the lighthouse.", "Nora edits the listing once more (Edit, Save). Ana, still with the short answer, presses Send Answers.");
    await center(A, SEND);
    await A.locator(SEND).click();
    await pause(A, 3500);
    D.say("Everything at once: the line under the button, the red mark at the answer, and Nora's change in the top box.");
    await lines(A, "a1 everything at once");
    await pause(A, 3000);
    await toTop(A, 3500);
    await center(A, "#a0");
    await pause(A, 2000);
    D.say("Ana presses again without fixing it: the line clears, the red mistake comes back (still true).");
    await A.locator(SEND).click();
    await pause(A, 4000);
    await lines(A, "a1 again, still short");
    D.say("She fixes the answer and presses Send Answers: it goes ahead.");
    await A.fill("#a0", "");
    await X.typeIn(A, "#a0", X.ANS[0], 10);
    await pause(A, 600);
    await A.locator(SEND).click();
    await A.waitForSelector("text=Sent your answers.", { timeout: 20000 }).catch(() => console.log("   ! not sent"));
    await pause(A, 3000);
    await lines(A, "a1 sent");
    D.say("Nora's page shows Ana's answers live.");
    await waitLive(N, "text=/Ana Silva sent/", 30000);
    await pause(N, 4000);
    await D.finish();
    X.noteScene(D, { page: "Session page" });
  });

  // ---------- A2: refusals for good: the team's pause (Add), Nora's End early (Request a time, reload, kept line) ----------
  scene("a2", async () => {
    const p = await pair({ liveRateCents: "30.00", liveMinutes: "30" });
    await X.sendWritten(p.ana, p.s);
    const { N, A } = await both(p, `/app/tests/${p.t}`, `/app/sessions/${p.s}`);
    const D = X.duo("a2-session-refusals", "Session page · refusals for good: a pause, then Nora ends Ana's work");
    D.start([N, A]);
    await X.unfold(A, "[data-add-more=written]");
    await center(A, "[data-add-more=written]");
    await pause(A, 2000);
    D.say("Ana opens Add to this answer and writes an addition.");
    await pause(A, 1500);
    await A.locator("[data-add-more=written]").first().evaluate((el) => el.click());
    await A.waitForSelector("[data-add-box] textarea", { timeout: 10000 }).catch(() => console.log("   ! no Add box"));
    await pause(A, 800);
    await X.typeIn(A, "[data-add-box] textarea", "One more thing: the lighthouse level has no checkpoint before the storm.", 10);
    await pause(A, 800);
    await waitPulse(A);
    D.say("The team pauses the test (an admin, off camera). Nora's page shows the pause.");
    await X.adminDo("pause-test", p.t);
    await N.reload();
    await pause(N, 1500);
    D.say("Ana presses Add to my answer before her page updates.");
    await A.locator("[data-add-send=written]").first().click();
    await pause(A, 2500);
    await center(A, "[data-paused-send]");
    await pause(A, 1500);
    D.say("Refused for good, under the button: “This test is paused right now, so your Add didn't go through.” The page redraws: Add goes away, the line stays where it was and the draft is kept.");
    await lines(A, "a2 paused Add");
    await pause(A, 6000);
    await lines(A, "a2 paused Add, later");
    D.say("Same for “This test is paused right now”: Send Answers, recording Send / Add, Request a time, Accept a call request. Charge, Let it go and Rate: “This test is paused, so …”. Never refused for a pause: Leave, Dispute, Switch / Keep, Cancel call.");
    await pause(A, 9000);
    D.say("Another press on the page (her Alerts, off and on) doesn't remove it: a line refused for a pause stays until the test resumes.");
    await toTop(A, 2500);
    await A.locator(ALERTS).first().click().catch(() => {});
    await pause(A, 1500);
    await A.locator(ALERTS).first().click().catch(() => {});
    await pause(A, 1500);
    await center(A, "[data-paused-send]");
    await pause(A, 2500);
    await lines(A, "a2 after another press");
    D.say("The team lifts the pause: the line goes and Add to my answer comes back, with her draft.");
    await X.adminDo("unpause-test", p.t);
    await N.reload();
    await waitLive(A, "[data-add-send=written]", 40000);
    await center(A, "[data-add-send=written]");
    await pause(A, 1500);
    await lines(A, "a2 after lift");
    await pause(A, 2000);
    D.say("Ana fills in a call request (a time and 30 minutes).");
    await fillRequest(A);
    await pause(A, 1000);
    await waitPulse(A);
    D.say("Nora ends Ana's work early in her window (End early, Ana, a reason, End their work now).");
    await noraEndsEarly(N);
    D.say("Ana presses Request a time before her page updates.");
    await center(A, REQ);
    await A.locator(REQ).first().click();
    await pause(A, 1500);
    D.say("Refused for good: her part is over. The page loads again at its top, and the line comes back where the button was (within 30 s of the press).");
    await A.waitForLoadState("load").catch(() => {});
    await pause(A, 6000);
    await lines(A, "a2 after End early");
    console.log("   [a2] url", A.url());
    await pause(A, 4000);
    D.say("Same for “Your part in this test has ended” (and “This test was stopped” after Nora's Stop): Send Answers, Add, recording Send / Add, Switch / Keep, call Accept / Decline / Withdraw, Cancel call. Leave is silent; Dispute, Charge and Rate keep their own rules.");
    await pause(A, 9000);
    await D.finish();
    X.noteScene(D, { page: "Session page" });
  });
};
