// C. The developer's test page (Nora), with Ana's actions in her own window causing the stops and refusals.
/* eslint-disable */
const X = require("../lib.cjs");
const { pause, center, lines, waitLive, waitPulse, visible, textOf, sql, own, utcNow, post, ok, go, nowIso } = X;
const { pair, both, SEND, REQ, toTop, fillRequest , reveal } = require("../common.cjs");
const JOINBTN = "#join-card button.btn";
/** Nora's next press must come before her page's next live update: wait for the one that just came. */
const noraFresh = (N) => waitPulse(N, 25000);

module.exports = (scene) => {
  // ---------- C1: applications (Accept refused after Ana withdraws), Pay (stopped once by Ana's addition), Pay more (stopped once by Ana leaving) ----------
  scene("c1", async () => {
    const p = await pair({ joinMode: "apply" }, false);
    const { N, A } = await both(p, `/app/tests/${p.t}`, `/app/find/${p.t}`);
    const D = X.duo("c1-test-page-applications-pay", "Test page · Accept, Pay and Pay more, with Ana's actions in between");
    D.start([N, A]);
    await center(A, "#join-card");
    await pause(A, 1500);
    D.say("Ana applies to join (Apply to join).");
    const noteBox = A.locator("#join-card textarea").first();
    if (await noteBox.count()) await X.typeIn(A, "#join-card textarea", "I can test on Windows this week.", 10);
    await A.locator(JOINBTN).first().click();
    await pause(A, 3500);
    D.say("Nora's page shows the application live.");
    await reveal(N, "li[id^=item-app-]");
    await pause(N, 2500);
    await noraFresh(N);
    D.say("Ana withdraws her application; Nora presses Accept before her page updates.");
    await A.locator("button:has-text('Withdraw application')").first().click().catch((e) => console.log("   ! withdraw:", e.message.split("\n")[0]));
    await pause(A, 1500);
    await N.locator("li[id^=item-app-] button:has-text('Accept')").first().click().catch((e) => console.log("   ! accept:", e.message.split("\n")[0]));
    await pause(N, 4000);
    D.say("Refused for good: “Ana Silva withdrew her application.” (Decline on a withdrawn application is silent.)");
    await lines(N, "c1 accept refused");
    await pause(N, 5000);
    D.say("Ana applies again (off camera); Nora accepts. Ana is in.");
    ok(await post(p.ana, `/api/tests/${p.t}/apply`, { ...go, seenAt: nowIso(), note: "" }), "apply again");
    await pause(A, 1500);
    await N.reload();
    await reveal(N, "li[id^=item-app-]");
    await N.locator("li[id^=item-app-] button:has-text('Accept')").first().click().catch((e) => console.log("   ! accept 2:", e.message.split("\n")[0]));
    await pause(N, 3000);
    const s = sql(`select id from "Contract" where "testId" = '${p.t}' and "testerId" = '${p.ana.uid}' limit 1`);
    await A.goto(`/app/sessions/${s}`);
    await A.waitForSelector("main h1");
    // Pay, stopped once by Ana's addition.
    await center(A, "#written");
    D.say("Ana sends her written answers.");
    await X.typeIn(A, "#a0", X.ANS[0], 6);
    await X.typeIn(A, "#a1", X.ANS[1], 6);
    await A.locator(SEND).click();
    await A.waitForSelector("text=Sent your answers.", { timeout: 20000 }).catch(() => {});
    await pause(A, 2000);
    await A.reload();
    await A.waitForSelector("main h1");
    await pause(A, 2500);
    await N.reload();
    await N.waitForSelector("main h1");
    const sub = X.subOf(s);
    const amt = N.locator(`#amt-${sub}`).first();
    await reveal(N, `#amt-${sub}`);
    await pause(N, 1500);
    D.say("Nora reads them and gets ready to pay $10.00 (the amount, the tick).");
    await amt.fill("10.00").catch(() => {});
    const tick = N.locator(`[data-pay-tick] input`).first();
    if (await tick.count()) await tick.check().catch(() => {});
    await pause(N, 1000);
    await X.unfold(A, "[data-add-more=written]");
    await center(A, "[data-add-more=written]");
    await pause(A, 1500);
    await A.locator("[data-add-more=written]").first().click();
    await A.waitForSelector("[data-add-box] textarea", { timeout: 10000 }).catch(async () => { console.log("   ! no Add box, again"); await A.locator("[data-add-more=written]").first().click().catch(() => {}); });
    await X.typeIn(A, "[data-add-box] textarea", "One more thing: the lighthouse level has no checkpoint before the storm.", 6);
    await noraFresh(N);
    D.say("Ana adds to her answer; Nora presses Pay before her page updates.");
    await A.locator("[data-add-send=written]").first().click();
    await pause(A, 1500);
    const payBtn = N.locator("button", { hasText: /^Pay$/ }).first();
    await payBtn.scrollIntoViewIfNeeded().catch(() => {});
    await payBtn.click().catch((e) => console.log("   ! pay:", e.message.split("\n")[0]));
    await pause(N, 3500);
    D.say("Stopped once: one line under Pay; “Ana Silva added to her answer …” is in Nora's top box (this stops Pay on that part whatever her Alerts).");
    await lines(N, "c1 pay line");
    await pause(N, 3000);
    await toTop(N, 3000);
    await payBtn.scrollIntoViewIfNeeded().catch(() => {});
    await pause(N, 1200);
    D.say("Pressed again: Nora pays $10.00 (fake card). Ana's page shows the payment live.");
    await payBtn.click().catch((e) => console.log("   ! pay 2:", e.message.split("\n")[0]));
    await pause(N, 5000);
    await lines(N, "c1 paid");
    console.log("   [c1] payments:", sql(`select string_agg(status || ' ' || "amountCents", ', ') from "Payment" where "submissionId" = '${sub}'`));
    // Pay more, stopped once by Ana leaving.
    await N.reload();
    await N.waitForSelector("main h1");
    const more = N.locator(`#amt-${sub}`).first();
    await reveal(N, `#amt-${sub}`);
    D.say("Nora wants to pay $2.00 more for the addition.");
    await more.fill("2.00").catch(() => {});
    const why = N.locator(`#why-${sub}`).first();
    if (await why.count()) await why.fill("Thanks for the extra detail on the lighthouse.").catch(() => {});
    await pause(N, 1000);
    await noraFresh(N);
    D.say("Ana leaves the test; Nora presses Pay more before her page updates.");
    await center(A, "#leave");
    await X.pressConfirm(A, A.locator("#leave button", { hasText: "Leave this test" }).first(), "Leave this test");
    await pause(A, 1500);
    const moreBtn = N.locator(`button`, { hasText: /^(Pay more|Pay)$/ }).first();
    await moreBtn.click().catch((e) => console.log("   ! pay more:", e.message.split("\n")[0]));
    await pause(N, 3500);
    D.say("Stopped once: one line; “Ana Silva left the test” is in the top box. Pressed again, it goes ahead.");
    await lines(N, "c1 pay more line");
    await pause(N, 3000);
    await moreBtn.click().catch((e) => console.log("   ! pay more 2:", e.message.split("\n")[0]));
    await pause(N, 5000);
    await lines(N, "c1 pay more paid");
    D.say("Same stop line for Nora's other presses (Accept / Decline, Invite, Cancel invite, Request a time, call answers, Cancel call, End early, Stop the test) when a tester's change comes in, under her test's Alerts.");
    await pause(N, 8000);
    await D.finish();
    X.noteScene(D, { page: "Test page" });
  });

  // ---------- C2: a call request (Accept refused after Ana withdraws), Invite / Invite anyway, Stop the test (stopped once by Ana's dispute? her request), team pause refusals ----------
  scene("c2", async () => {
    const p = await pair({ liveRateCents: "30.00", liveMinutes: "30", devices: ["iPad"] });
    // (a name no other account in the media database has: Invite's search finds people by name)
    const ben = await X.account(`${p.tag}b`, "Bram Okafor", "tester", "he");
    const { N, A } = await both(p, `/app/tests/${p.t}`, `/app/sessions/${p.s}`);
    const D = X.duo("c2-test-page-calls-invite-stop", "Test page · a call request, Invite anyway, Stop the test, the team's pause");
    D.start([N, A]);
    D.say("Ana asks Nora for a call (Request a time).");
    await fillRequest(A);
    await A.locator(REQ).first().click();
    await pause(A, 3000);
    await reveal(N, "li[id^=req-]");
    await pause(N, 2000);
    await noraFresh(N);
    D.say("Ana withdraws her request; Nora presses Accept before her page updates.");
    await reveal(A, "[data-your-requests]");
    const wd = A.locator("[data-your-requests] button:has-text('Withdraw')").first();
    await wd.click().catch((e) => console.log("   ! withdraw:", String(e.message).slice(0, 100)));
    await pause(A, 1200);
    await N.locator("li[id^=req-] button:has-text('Accept')").first().click().catch((e) => console.log("   ! accept:", String(e.message).slice(0, 100)));
    await pause(N, 4000);
    D.say("Refused for good: the line under Accept says Ana withdrew this request.");
    await lines(N, "c2 accept refused");
    await pause(N, 5000);
    // Invite anyway (Ben lacks the iPad the test needs); stopped once by Ana's new request.
    await N.evaluate(() => { const d = document.getElementById("invite"); if (d) d.open = true; });
    await center(N, "#invite");
    D.say("Nora invites Bram: she finds him and ticks him. The test needs an iPad, which Bram doesn't list.");
    await N.locator("input[aria-label='Find testers']").fill("Bram Okafor");
    await pause(N, 2500);
    await N.locator("#invite input[type=checkbox][aria-label='Bram Okafor']").first().check().catch((e) => console.log("   ! tick Ben:", String(e.message).slice(0, 100)));
    await N.locator("#invite button.btn", { hasText: /^Invite$/ }).first().click().catch(() => {});
    await pause(N, 3000);
    D.say("Invite asks first: Bram is missing what the test needs. Nora can Invite anyway.");
    console.log("   [c2] invite anyway box:", await textOf(N, "[data-invite-anyway]"));
    await fillRequest(A, 4);
    await pause(N, 1500);
    await noraFresh(N);
    D.say("Ana sends a new call request; Nora presses Invite anyway before her page updates.");
    await A.locator(REQ).first().click();
    await pause(A, 800);
    await N.locator("[data-invite-anyway] button:has-text('Invite anyway')").first().click().catch((e) => console.log("   ! invite anyway:", String(e.message).slice(0, 100)));
    await pause(N, 3500);
    D.say("Stopped once: one line; Ana's request is in the top box. Pressed again: Bram is invited.");
    await lines(N, "c2 invite line");
    await pause(N, 2500);
    await N.locator("[data-invite-anyway] button:has-text('Invite anyway')").first().click().catch((e) => console.log("   ! invite again:", String(e.message).slice(0, 100)));
    await pause(N, 4000);
    await lines(N, "c2 invited");
    console.log("   [c2] Bram's invite:", sql(`select string_agg(status, ',') from "Invite" where "testerId" = '${ben.uid}'`));
    // Stop the test: stopped once by Ana's answers.
    await center(A, "#written");
    await A.fill("#a0", X.ANS[0]);
    await A.fill("#a1", X.ANS[1]);
    await N.evaluate(() => scrollTo(0, 0));
    await N.locator("button", { hasText: "Stop the test" }).first().click();
    const dlg = N.locator("dialog[open]");
    await dlg.waitFor({ state: "visible", timeout: 5000 }).catch(() => console.log("   ! no Stop dialog"));
    await dlg.locator("#stop-reason").fill(X.STOP_WHY).catch(() => {});
    await noraFresh(N);
    D.say("Ana sends her written answers; Nora presses Stop the test (reason written) before her page updates.");
    await A.locator(SEND).click();
    await pause(A, 800);
    await dlg.locator("button[data-confirm]").click().catch((e) => console.log("   ! stop confirm:", String(e.message).slice(0, 100)));
    await pause(N, 3500);
    D.say("Stopped once: one line under Stop the test; “Ana Silva sent her written answers” is in the top box.");
    await lines(N, "c2 stop line");
    await pause(N, 4000);
    D.say("Same for End early. Nora doesn't press again here: the test stays open for the team's pause next.");
    await pause(N, 4000);
    // The team's pause: Nora's Request a time refused.
    await N.reload();
    await N.waitForSelector("main h1");
    await noraFresh(N);
    D.say("The team pauses the test (an admin, off camera). Nora presses Accept on Ana's call request before her page updates.");
    await X.adminDo("pause-test", p.t);
    await reveal(N, "li[id^=req-]");
    await N.locator("li[id^=req-] button:has-text('Accept')").first().click().catch((e) => console.log("   ! accept paused:", e.message.split("\n")[0]));
    await pause(N, 5000);
    D.say("Refused for good: “The team paused this test, so your Accept didn't go through.” Nora's page goes to the test's top, where the banner names the press.");
    await lines(N, "c2 paused accept");
    console.log("   [c2] url", N.url());
    await pause(N, 6000);
    D.say("Same while the team's pause is on: Pay, Pay more, Invite, Request a time, Next round … (Stop the test, End early and Cancel call still work). A hold reads “Your tests are paused”, a suspension “Your account is suspended”.");
    await pause(N, 9000);
    await D.finish();
    X.noteScene(D, { page: "Test page" });
  });
};
